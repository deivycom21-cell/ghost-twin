def _code(s: str) -> str:
    s = s.replace("\n", "\\n")
    if len(s) > 160:
        s = f"{s[:120]}… ({len(s)} chars)"
    fence = "``" if "`" in s else "`"
    pad = " " if fence == "``" else ""
    return f"{fence}{pad}{s}{pad}{fence}"


def _block(text: str, lang: str = "text") -> str:
    fence = "````" if "```" in text else "```"
    return f"{fence}{lang}\n{text.rstrip()}\n{fence}"


def _fmt_ts(ts: float | None) -> str:
    if not ts:
        return "-"
    return datetime.fromtimestamp(ts, tz=timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def _rel(path: Path, base: Path) -> str:
    try:
        return Path(os.path.relpath(path, base)).as_posix()
    except ValueError:
        return path.as_posix()


def _attack_cmd(run: dict[str, Any]) -> str:
    cfg = run.get("config") or {}
    parts = [f"ghost-twin attack {run['target']}"]
    if cfg.get("users"):
        parts.append(f"--users {cfg['users']}")
    if cfg.get("seed") is not None:
        parts.append(f"--seed {cfg['seed']}")
    return " ".join(parts)


class ReportBuilder:
    def __init__(self, store: Store, run_id: int, *, data_dir: str | Path,
                 report_dir: str | Path | None = None, lang: str = "en", ai: Any = None):
        self.store = store
        self.run_id = run_id
        self.data_dir = Path(data_dir)
        self.report_dir = Path(report_dir) if report_dir else Path.cwd()
        self.lang = lang if lang in T else "en"
        self.t = T[self.lang]
        self.ai = ai

    def bugs(self) -> list[Bug]:
        return group_findings(self.store.findings(self.run_id))

    # ------------------------------------------------------------------ sections
    def _header(self, run: dict, sessions: list[dict], raw: int, bugs: list[Bug]) -> list[str]:
        t = self.t
        dur = "-"
        if run.get("finished_at"):
            dur = f"{run['finished_at'] - run['started_at']:.0f}s"
        personas = Counter(s["persona"] for s in sessions)
        agents = ", ".join(f"{n}×{p}" for p, n in sorted(personas.items()))
        sev = Counter(b.severity.value for b in bugs)
        sev_line = " · ".join(f"{SEV_ICON[s]} {sev[s]} {s}" for s in SEV_ICON if sev.get(s))
        lines = [
            f"# 🐛 {t['title']}",
            "",
            f"> **{t['target']}:** {run['target']} · **{t['run']}:** #{run['id']} · "
            f"**{t['started']}:** {_fmt_ts(run['started_at'])} · **{t['duration']}:** {dur} · "
            f"**{t['seed']}:** {run.get('seed')}",
            f"> **{t['agents']}:** {agents or '-'}",
            ">",
            f"> **{t['unique'].format(n=len(bugs), raw=raw)}**" + (f" — {sev_line}" if sev_line else ""),
            "",
        ]
        return lines

    def _summary(self, bugs: list[Bug]) -> list[str]:
        t = self.t
        lines = [f"## {t['summary']}", "",
                 f"| # | {t['sev']} | {t['type']} | {t['where']} | {t['hits']} |",
                 "|---|---|---|---|---|"]
        for i, b in enumerate(bugs, 1):
            f = b.first
            title = f["title"].replace("|", "\\|")
            lines.append(f"| [BUG-{i:03d}](#bug-{i:03d}) | {SEV_ICON[b.severity.value]} "
                         f"{b.severity.value} | `{f['kind']}` | {title} | {len(b.occurrences)} |")
        lines.append("")
        return lines

    def _steps(self, f: dict) -> list[str]:
        t = self.t
        if f["kind"] == "server_crash":
            return []
        sid, upto = f.get("session_id"), f.get("step_idx")
        if sid is None or upto is None:
            return []
        steps = self.store.steps(sid, upto)
        if not steps:
            return []
        if f.get("persona") == "api_fuzzer":
            return [f"### {t['steps']}", "", f"1. {steps[-1]['description']}", ""]
        # A direct navigation resets the page: earlier steps don't matter for reproduction.
        gotos = [i for i, s in enumerate(steps) if s["kind"] == "goto"]
        if gotos:
            steps = steps[gotos[-1]:]
        lines = [f"### {t['steps']}", ""]
        if len(steps) > MAX_STEPS_SHOWN:
            tail = steps[-(MAX_STEPS_SHOWN - 1):]
            omitted = len(steps) - len(tail) - 1
            lines += [f"1. {steps[0]['description']}", "",
                      f"_{t['earlier'].format(n=omitted)}_", ""]
            for i, s in enumerate(tail):
                lines.append(f"{omitted + 2 + i}. {s['description']}")
        else:
            for i, s in enumerate(steps, 1):
                lines.append(f"{i}. {s['description']}")
        return lines + [""]

    def _artifacts(self, f: dict, artifacts: list[dict]) -> list[str]:
        sid = f.get("session_id")
        if sid is None:
            return []
        mine = [a for a in artifacts if a["session_id"] == sid]
        shots = [a for a in mine if a["kind"] == "screenshot"]
        step = f.get("step_idx") or 0
        shot = next((a for a in shots if (a["step_idx"] or 0) >= step), shots[-1] if shots else None)
        videos = [a for a in mine if a["kind"] == "video"]
        if not shot and not videos:
            return []
        t = self.t
        lines = [f"### {t['artifacts']}", ""]
        if shot:
            lines.append(f"- {t['screenshot']}: `{_rel(self.data_dir / shot['path'], self.report_dir)}`")
        for v in videos:
            lines.append(f"- {t['video']}: `{_rel(self.data_dir / v['path'], self.report_dir)}`")
        lines.append("")
        return lines

    def _bug(self, i: int, b: Bug, artifacts: list[dict]) -> list[str]:
        t = self.t
        f = b.first
        sev = b.severity.value
        lines = [f"## BUG-{i:03d}", "",
                 f"**{SEV_ICON[sev]} [{sev.upper()}] {f['title']}**", ""]
        meta = [f"- **{t['type']}:** `{f['kind']}`",
                f"- **{t['found_by']}:** {', '.join(b.personas)}" + (
                    f" (session #{f['session_id']})" if f.get("session_id") else ""),
                f"- **{t['url']}:** `{f['url']}`"]
        if f.get("method") and f["kind"] not in {"console_error", "js_exception", "server_crash"}:
            meta.append(f"- **{t['method']}:** `{f['method']}`")
        if f.get("status"):
            meta.append(f"- **{t['status']}:** `{f['status']}`")
        if f.get("param"):
            meta.append(f"- **{t['param']}:** `{f['param']}`")
        if f.get("payload") is not None:
            meta.append(f"- **{t['payload']}:** {_code(f['payload'])}")
        others = [p for p in b.payloads if p != f.get("payload")]
        if others:
            meta.append(f"- **{t['other_payloads']}:** " + ", ".join(_code(p) for p in others[:5]))
        meta.append(f"- **{t['occ']}:** {len(b.occurrences)}")
        extra_urls = [u for u in b.urls if u != f["url"]]
        if extra_urls:
            meta.append(f"- **{t['also']}:** " + ", ".join(f"`{u}`" for u in extra_urls[:5]))
        lines += meta + [""]
        lines += self._steps(f)
        curl = (f.get("detail") or {}).get("curl")
        if curl:
            lines += [f"### {t['curl']}", "", _block(curl, "bash"), ""]
        if f.get("evidence"):
            lines += [f"### {t['evidence']}", "", _block(f["evidence"][:2500]), ""]
        lines += self._artifacts(f, artifacts)
        hint = hint_for(f["kind"], self.lang)
        if hint:
            lines += [f"### {t['fix']}", "", hint, ""]
        lines += ["---", ""]
        return lines

    def _ai_section(self, run: dict, bugs: list[Bug]) -> list[str]:
        if self.ai is None or not bugs:
            return []
        from ghost_twin.ai.tasks import summarize_bugs

        try:
            text = summarize_bugs(self.ai, run["target"], bugs, self.lang)
        except Exception:
            return []
        if not text.strip():
            return []
        return [f"## {self.t['ai']}", "", text.strip(), ""]

    # ------------------------------------------------------------------ build
    def build(self) -> str:
        run = self.store.get_run(self.run_id)
        if run is None:
            raise ValueError(f"run #{self.run_id} not found")
        sessions = self.store.sessions(self.run_id)
        raw = self.store.findings(self.run_id)
        bugs = group_findings(raw)
        artifacts = self.store.artifacts(self.run_id)
        t = self.t
        lines = self._header(run, sessions, len(raw), bugs)
        if not bugs:
            lines += [t["none"], ""]
        else:
            lines += [f"## {t['agent_title']}", "",
                      t["agent_body"].format(cmd=_attack_cmd(run)), ""]
            lines += self._summary(bugs)
            lines += self._ai_section(run, bugs)
            lines += ["---", ""]
            for i, b in enumerate(bugs, 1):
                lines += self._bug(i, b, artifacts)
        lines += [f"<sub>{t['generated'].format(v=__version__)}</sub>", ""]
        return "\n".join(lines)


def build_report(store: Store, run_id: int, *, data_dir: str | Path,
                 report_dir: str | Path | None = None, lang: str = "en", ai: Any = None) -> str:
    return ReportBuilder(store, run_id, data_dir=data_dir, report_dir=report_dir, lang=lang,
                         ai=ai).build()


def write_report(store: Store, run_id: int, out: str | Path, *, data_dir: str | Path,
                 lang: str = "en", ai: Any = None) -> Path:
    """Write the report to ``out`` and keep a copy next to the run's artifacts.

    Each copy gets artifact paths relative to its own location. AI calls are cached, so the
    second build does not spend tokens twice.
    """
    out = Path(out)
    run_copy = Path(data_dir) / "runs" / str(run_id) / "BUG_REPORT.md"
    for target in dict.fromkeys([out.resolve(), run_copy.resolve()]):
        target.parent.mkdir(parents=True, exist_ok=True)
        text = build_report(store, run_id, data_dir=data_dir, report_dir=target.parent,
                            lang=lang, ai=ai)
        target.write_text(text, encoding="utf-8")
    return out
